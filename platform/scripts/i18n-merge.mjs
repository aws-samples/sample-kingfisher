// Merge translation shards into en.ts and validate placeholder consistency.
// Usage: node scripts/i18n-merge.mjs
// Sources: /tmp/qa2/i18n_out/out_*.json and const_*.json (key=zh source, value=en).
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve(process.cwd(), "src");
const EN_PATH = path.resolve(SRC, "lib/i18n/messages/en.ts");
const OUT_DIR = "/tmp/qa2/i18n_out";

function existingEntries() {
  const txt = fs.readFileSync(EN_PATH, "utf8");
  const map = {};
  const re = /^\s*"((?:[^"\\]|\\.)*)":\s*"((?:[^"\\]|\\.)*)",?\s*$/gm;
  let m;
  while ((m = re.exec(txt))) {
    map[JSON.parse(`"${m[1]}"`)] = JSON.parse(`"${m[2]}"`);
  }
  return map;
}

// {word} placeholders, ignoring {{...}} double-brace template syntax
function placeholders(s) {
  const set = new Set();
  const re = /(?<!\{)\{(\w+)\}(?!\})/g;
  let m;
  while ((m = re.exec(s))) set.add(m[1]);
  return set;
}
function sameSet(a, b) {
  if (a.size !== b.size) return false;
  for (const x of a) if (!b.has(x)) return false;
  return true;
}

const merged = { ...existingEntries() };
const warnings = [];
let added = 0;
const shards = fs.readdirSync(OUT_DIR).filter((n) => /^(out|const)_\d+\.json$/.test(n)).sort();
for (const name of shards) {
  const obj = JSON.parse(fs.readFileSync(path.join(OUT_DIR, name), "utf8"));
  for (const [zh, en] of Object.entries(obj)) {
    if (!sameSet(placeholders(zh), placeholders(en))) {
      warnings.push(`placeholder mismatch [${name}]: "${zh}" -> "${en}"`);
    }
    if (!(zh in merged)) added++;
    merged[zh] = en;
  }
}

if (warnings.length) {
  console.log("WARN placeholder check:");
  for (const w of warnings) console.log("  " + w);
} else {
  console.log("OK placeholder consistency check passed");
}
console.log(`shards merged: ${shards.length}, total entries: ${Object.keys(merged).length} (added ${added})`);

const header = `// English dictionary: zh source string -> en translation (single source of truth for i18n).
//
// Rules:
//   - key = the zh source string used in t("...") calls, must match verbatim (punctuation/space).
//   - missing entries degrade to Chinese in en mode (no error).
//   - interpolation uses {name} placeholders matching the zh source, e.g. "共 {n} 条": "{n} total".
//   - only UI chrome; business data (datasource names, columns, GenBI answers) is NOT here.
//
// Generated by scripts/i18n-merge.mjs (source: full-site t() extraction + sharded translation).
// Small additions can be hand-edited; large batches go through i18n-extract.mjs -> translate -> i18n-merge.mjs.

export const EN: Record<string, string> = {
`;
const keys = Object.keys(merged).sort((a, b) => a.localeCompare(b, "zh"));
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(merged[k])},`).join("\n");
fs.writeFileSync(EN_PATH, header + body + "\n};\n", "utf8");
console.log(`written: ${EN_PATH}`);
