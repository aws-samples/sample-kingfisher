// 为单个 EMR Serverless 引擎作业生成 Airflow DAG(MWAA 调度)。
// DAG 用 boto3 调 emr-serverless:确保 per-作业 application 已启动 → start_job_run → 轮询终态。
// sparkSubmitParameters/entryPoint 在发布时(TS 侧)算好烘焙进 DAG(与"立即运行"同一套参数),
// DAG 只做 boto3 调用,不在 Python 侧重造复杂参数逻辑。调度运行同样写 bgp-task-runs(监控/运行历史复用)。
//
// 前提:作业至少成功运行过一次(application 已建、脚本已上传 S3)。发布 schedule 路由会 ensure 这些。

import { homeRegion } from "@/lib/place/home-region";
import type { EmrEngineJob } from "./types";
// @kf-batch 52-P52.2-W2a-run-stamp — MWAA 旁路建行点,章在生成时注入(片段单作者)。
// @kf-batch 50-WP15-airflow-serverless(T-12)台账行键唯一作者
import { pyRunKeyFields } from "@/lib/monitor/run-key";
import { pythonStampFields, resolveRunStamp } from "@/lib/monitor/run-records";
// @kf-batch 37-emr-run-date —— 业务日期参数在 Python 里按同一张表算(单一作者;与手动提交 provider.ts 同一组参数名)
import { RUN_PARAMS_PY } from "@/lib/etl/run-params-py";

export interface EmrDagContext {
  entryPoint: string;              // 脚本 S3 URI(该 target 的脚本桶)
  sparkSubmitParameters: string;   // 完整 spark-submit 参数(规格+S3Tables+用户conf;表桶 / jar 都是该 target 的)
  executionRoleArn: string;        // 🔴 该 target 自己的 EMR 执行角色(非 home 绝不是 home 角色)
  applicationId: string;           // 该 target 上的 application
  logUri: string;
  entryPointArguments: string[];
  // @kf-batch 50-WP13-mwaa-region —— 逐 target 扇出(每份 DAG 由该 target 自己的 MWAA 执行,SPEC v3.26 §3.14)
  /** **执行面** region(emr-serverless 客户端)。缺省 env(即 home,逐字节等价) */
  execRegion?: string;
  /** **控制面** region(run 台账 DDB)。缺省 env;非 home 也必须是 home —— 台账控制面单份 */
  ctrlRegion?: string;
  /** 本份 DAG 服务于哪个 target(run 记录盖的章;缺省 = 作业绑定的第一个 / home) */
  targetId?: string;
  /** 本份 DAG 的 dag_id(非 home 带 target 后缀,见 dagIdForTarget;缺省 = 存量口径) */
  dagId?: string;
}

const DAG_ID_RE = /^[A-Za-z0-9_.-]{1,200}$/;

export function generateEmrJobDag(job: EmrEngineJob, ctx: EmrDagContext): string {
  const dagId = ctx.dagId || job.airflowDagId || `bgp_engine_${job.jobId}`;
  if (!DAG_ID_RE.test(dagId)) throw new Error(`非法 dagId ${JSON.stringify(dagId)}:它会被拼进生成的 Python 源码`);
  const schedule = job.cronExpression || "None";
  // @kf-batch 50-WP13-mwaa-region
  // 🔴 拆执行面 / 控制面两个 region(与 lib/etl/dag-generator.ts 同一口径):原来 emr 与 ddb 共用一个 `region`,
  //    非 home 时 run 台账会写到**该区**根本不存在的表(控制面单份在 home)⇒ 定时 run 无声不入账。
  const ctrlRegion = ctx.ctrlRegion || homeRegion();
  const execRegion = ctx.execRegion || ctrlRegion;
  const emrStamp = resolveRunStamp(job, ctx.targetId); // 章 = 这份 DAG 真正执行的 target(值非法即抛)
  const stampFields = pythonStampFields(emrStamp);
  // @kf-batch 50-WP15-airflow-serverless(T-12)台账行键(唯一作者 lib/monitor/run-key.ts;target 取自章,不再从可选入参取)
  const runKeyFields = pyRunKeyFields({ taskIdExpr: "JOB_ID", rawExpr: "run_id", targetId: emrStamp.targetId });

  return `"""Auto-generated by BigData Governance Platform — EMR Serverless engine job (code-first)"""
from datetime import datetime
from airflow import DAG
from airflow.operators.python import PythonOperator
import boto3, time, re, sys

EXEC_REGION = "${execRegion}"
CTRL_REGION = "${ctrlRegion}"
emr = boto3.client("emr-serverless", region_name=EXEC_REGION)
ddb = boto3.resource("dynamodb", region_name=CTRL_REGION)

JOB_ID = "${job.jobId}"
APPLICATION_ID = "${ctx.applicationId}"
EXEC_ROLE = ${JSON.stringify(ctx.executionRoleArn)}
ENTRY_POINT = ${JSON.stringify(ctx.entryPoint)}
ENTRY_ARGS = ${JSON.stringify(ctx.entryPointArguments || [])}
SPARK_PARAMS = ${JSON.stringify(ctx.sparkSubmitParameters)}
LOG_URI = ${JSON.stringify(ctx.logUri)}
${RUN_PARAMS_PY}

def _ensure_started():
    # per-作业 application 空闲可能被 EMR 自动 STOP;调度触发前确保 STARTED。
    st = emr.get_application(applicationId=APPLICATION_ID)["application"]["state"]
    if st in ("STOPPED", "CREATED"):
        emr.start_application(applicationId=APPLICATION_ID)
    for _ in range(40):
        st = emr.get_application(applicationId=APPLICATION_ID)["application"]["state"]
        if st == "STARTED":
            return
        if st in ("STOPPING", "TERMINATED"):
            raise Exception(f"application {APPLICATION_ID} in bad state {st}")
        time.sleep(15)
    raise Exception(f"application {APPLICATION_ID} not STARTED in time")

def run_job(**ctx):
    _ensure_started()
    # 业务日期取 Airflow 逻辑日期(与 Glue 定时作业同口径);参数**追加**在用户入参之后,与平台「立即运行」同一张表、同一顺序。
    ds = ctx.get("ds") or datetime.utcnow().strftime("%Y-%m-%d")
    resp = emr.start_job_run(
        applicationId=APPLICATION_ID,
        executionRoleArn=EXEC_ROLE,
        name="${job.name}-sched",
        jobDriver={"sparkSubmit": {
            "entryPoint": ENTRY_POINT,
            "entryPointArguments": ENTRY_ARGS + bgp_run_param_argv(ds),
            "sparkSubmitParameters": SPARK_PARAMS,
        }},
        configurationOverrides={"monitoringConfiguration": {"s3MonitoringConfiguration": {"logUri": LOG_URI}}},
    )
    native = resp["jobRunId"]
    print(f"Started EMR job run {native}")
    ti = ctx.get("ti")
    if ti: ti.xcom_push(key="native_run_id", value=native)
    while True:
        jr = emr.get_job_run(applicationId=APPLICATION_ID, jobRunId=native)["jobRun"]
        state = jr["state"]
        if state in ("SUCCESS", "FAILED", "CANCELLED"):
            break
        time.sleep(15)
    if state != "SUCCESS":
        raise Exception(f"EMR job run {native} ended with {state}: {jr.get('stateDetails','')}")
    print(f"EMR job run {native} SUCCESS")

def _record(run_id, status, **ctx):
        # 🔴 T-12(2026-09-07 真环境):台账 runId 必须带 targetId 段,否则同一作业绑两个 region 时
        #   两区的 run 行同键、**后写盖掉先写**(实测两区都跑成功而台账只剩一行)。口径单一作者 = lib/monitor/run-key.ts。
    try:
        ddb.Table("bgp-task-runs").put_item(Item={
            "taskId": JOB_ID, ${runKeyFields}, "taskType": "emr-serverless",
            "status": status, "startedAt": datetime.utcnow().isoformat() + "Z",
            "finishedAt": datetime.utcnow().isoformat() + "Z",
            "triggeredBy": "schedule", "airflowDagId": "${dagId}",
            ${stampFields},
        })
        ddb.Table("bgp-engine-jobs").update_item(
            Key={"userId": "default-user", "jobId": JOB_ID},
            UpdateExpression="SET lastRunStatus = :s, #st = :s, updatedAt = :t",
            ExpressionAttributeNames={"#st": "status"},
            ExpressionAttributeValues={":s": status, ":t": datetime.utcnow().isoformat() + "Z"},
        )
    except Exception as e:
        # 🔴 T-12「写不成即拒」:台账是运行历史与成本归因的唯一真值源。这里是**任务**(done),抛出去让本次 run 显红,
        #   而不是吞掉、留下一次「看板上不存在」的成功运行。失败回调侧另有 try 包裹,避免掩盖原始错误。
        print("record failed", e)
        raise

def on_success(**ctx):
    rid = ctx.get("dag_run").run_id if ctx.get("dag_run") else "manual"
    _record(rid, "succeeded")

def on_failure(ctx):
    rid = ctx.get("dag_run").run_id if ctx.get("dag_run") else "manual"
    _record(rid, "failed")

with DAG(
    dag_id="${dagId}",
    schedule_interval=${schedule === "None" ? "None" : `"${schedule}"`},
    start_date=datetime(2024, 1, 1),
    catchup=False,
    tags=["bgp", "engine", "emr-serverless"],
    on_failure_callback=on_failure,
) as dag:
    run = PythonOperator(task_id="run_job", python_callable=run_job)
    done = PythonOperator(task_id="done", python_callable=on_success, trigger_rule="all_success")
    run >> done
`;
}
